/** A control's tags (an untagged one counts as advanced and core-less: only Open shows it). */
export function tagsOf(kind: ControlKind, id: string): ControlTags {
  return CONTROL_TAGS[kind][id] ?? { tags: [], level: 'advanced' };
}

