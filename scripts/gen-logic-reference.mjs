#!/usr/bin/env node
// Writes docs/logic-reference.md from the logic node catalog (P7.5). The Help guide builds the same page at runtime.
//   node scripts/gen-logic-reference.mjs          -> writes the file
//   node scripts/gen-logic-reference.mjs --check  -> exits 1 when the file is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'docs/logic-reference.md');
const r = await build({
  entryPoints: [resolve(ROOT, 'src/core/logic/reference.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
});
const mod = await import(`data:text/javascript;base64,${Buffer.from(r.outputFiles[0].text).toString('base64')}`);
const md = `<!-- Generated by scripts/gen-logic-reference.mjs from src/core/logic/catalog. Do not edit. -->\n\n${mod.logicReferenceMarkdown()}`;
if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(OUT, 'utf8');
  } catch {}
  if (cur !== md) {
    console.error('docs/logic-reference.md is out of date: run node scripts/gen-logic-reference.mjs');
    process.exit(1);
  }
  console.log('docs/logic-reference.md is up to date');
} else {
  writeFileSync(OUT, md);
  console.log(`wrote ${OUT}`);
}
